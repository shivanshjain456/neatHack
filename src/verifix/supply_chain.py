"""Supply-chain integrity for VeriFix's own releases.

* ``parse_lock`` / ``hashed_lock``: pinned dependencies, with every PyPI file digest recorded so
  ``pip install --require-hashes`` refuses any substituted artifact (lockfile integrity).
* ``cyclonedx_sbom``: CycloneDX 1.5 JSON SBOM for one artifact. It is deterministic: the serial
  number is derived from the content, and the timestamp comes from SOURCE_DATE_EPOCH.
* ``osv_scan`` + ``vuln_policy``: software composition analysis against the OSV database. High
  and critical findings fail unless allowlisted with a justification and an expiry date.
* ``deterministic_zip``: byte-identical archives from identical inputs (reproducible builds).
* ``provenance_statement`` / ``verify_provenance``: in-toto Statement v1 with a SLSA v1
  provenance predicate. The deploy script verifies it before it uploads anything.
"""

from __future__ import annotations

import datetime as dt
import hashlib
import json
import os
import re
import uuid
import zipfile
from pathlib import Path
from typing import Any, Iterable

import httpx

FIXED_ZIP_TIME = (1980, 1, 1, 0, 0, 0)
SLSA_PREDICATE = "https://slsa.dev/provenance/v1"
INTOTO_STATEMENT = "https://in-toto.io/Statement/v1"
BUILD_TYPE = "https://github.com/shivanshjain456/neatHack/blob/main/docs/SUPPLY_CHAIN.md#lambda-zip-v1"


def sha256_file(path: str | Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def normalize(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def parse_lock(path: str | Path) -> list[tuple[str, str]]:
    out = []
    for raw in Path(path).read_text(encoding="utf-8").splitlines():
        line = raw.split("#", 1)[0].strip()
        if not line or line.startswith("-"):
            continue
        m = re.match(r"^([A-Za-z0-9_.\-\[\]]+)==([^\s;\\]+)", line)
        if not m:
            raise ValueError(f"unpinned or unsupported lock line: {raw!r}")
        out.append((re.sub(r"\[.*\]", "", m.group(1)), m.group(2)))
    return out


def pypi_release(name: str, version: str, client: httpx.Client) -> dict[str, Any]:
    r = client.get(f"https://pypi.org/pypi/{name}/{version}/json")
    r.raise_for_status()
    return r.json()


def hashed_lock(pins: list[tuple[str, str]], client: httpx.Client) -> tuple[str, dict[str, dict[str, Any]]]:
    """Return (lock text with --hash for every distribution file, metadata by package)."""
    lines, meta = [
        "# Generated by scripts/supply_chain.py lock. Do not edit by hand.",
        "# Every PyPI file digest is listed; install with: pip install --require-hashes -r requirements-runtime.hashes.lock",
    ], {}
    for name, version in pins:
        rel = pypi_release(name, version, client)
        digests = sorted({u["digests"]["sha256"] for u in rel.get("urls", []) if u.get("digests", {}).get("sha256")})
        if not digests:
            raise RuntimeError(f"PyPI lists no files for {name}=={version}")
        info = rel.get("info", {})
        lic = (info.get("license_expression") or info.get("license") or "").strip()
        if not lic or len(lic) > 80:
            lic = next((c.split("::")[-1].strip() for c in info.get("classifiers", []) if c.startswith("License ::")), lic[:80] or "NOASSERTION")
        meta[normalize(name)] = {"name": name, "version": version, "sha256": digests, "license": lic}
        lines.append(f"{name}=={version} \\")
        lines.extend([f"    --hash=sha256:{d} \\" for d in digests[:-1]] + [f"    --hash=sha256:{digests[-1]}"])
    return "\n".join(lines) + "\n", meta


def source_date() -> dt.datetime:
    epoch = os.environ.get("SOURCE_DATE_EPOCH")
    return dt.datetime.fromtimestamp(int(epoch), dt.timezone.utc) if epoch else dt.datetime(2026, 10, 11, tzinfo=dt.timezone.utc)


def cyclonedx_sbom(meta: dict[str, dict[str, Any]], artifact_name: str, artifact_sha256: str | None, app_version: str) -> dict[str, Any]:
    comps = []
    for key in sorted(meta):
        m = meta[key]
        comps.append({
            "type": "library", "bom-ref": f"pkg:pypi/{key}@{m['version']}", "name": m["name"], "version": m["version"],
            "purl": f"pkg:pypi/{key}@{m['version']}",
            "hashes": [{"alg": "SHA-256", "content": d} for d in m["sha256"]],
            "licenses": [{"license": {"name": m["license"]}}] if m.get("license") else [],
        })
    body = json.dumps(comps, sort_keys=True)
    serial = uuid.uuid5(uuid.NAMESPACE_URL, f"verifix:{artifact_name}:{artifact_sha256}:{hashlib.sha256(body.encode()).hexdigest()}")
    root = {"type": "application", "bom-ref": "verifix", "name": "verifix", "version": app_version}
    if artifact_sha256:
        root["hashes"] = [{"alg": "SHA-256", "content": artifact_sha256}]
    return {
        "bomFormat": "CycloneDX", "specVersion": "1.5", "serialNumber": f"urn:uuid:{serial}", "version": 1,
        "metadata": {"timestamp": source_date().strftime("%Y-%m-%dT%H:%M:%SZ"), "component": root,
                     "tools": {"components": [{"type": "application", "name": "verifix-supply-chain", "version": "1.0.0"}]},
                     "properties": [{"name": "verifix:artifact", "value": artifact_name}]},
        "components": comps,
        "dependencies": [{"ref": "verifix", "dependsOn": [c["bom-ref"] for c in comps]}],
    }


SEVERITY_ORDER = {"LOW": 1, "MODERATE": 2, "MEDIUM": 2, "HIGH": 3, "CRITICAL": 4}


def _severity(vuln: dict[str, Any]) -> str:
    sev = (vuln.get("database_specific") or {}).get("severity")
    if isinstance(sev, str) and sev.upper() in SEVERITY_ORDER:
        return sev.upper()
    for aff in vuln.get("affected", []):
        s = (aff.get("ecosystem_specific") or {}).get("severity") or (aff.get("database_specific") or {}).get("severity")
        if isinstance(s, str) and s.upper() in SEVERITY_ORDER:
            return s.upper()
    for s in vuln.get("severity", []):
        score = s.get("score", "")
        m = re.search(r"CVSS:[0-9.]+/.*", score)
        if m:
            return "HIGH"  # vector present without a database rating: treat conservatively
    return "UNKNOWN"


def osv_scan(pins: list[tuple[str, str]], client: httpx.Client) -> list[dict[str, Any]]:
    queries = [{"package": {"name": n, "ecosystem": "PyPI"}, "version": v} for n, v in pins]
    r = client.post("https://api.osv.dev/v1/querybatch", json={"queries": queries})
    r.raise_for_status()
    findings = []
    for (name, version), res in zip(pins, r.json().get("results", [])):
        for v in res.get("vulns", []) or []:
            full = client.get(f"https://api.osv.dev/v1/vulns/{v['id']}")
            full.raise_for_status()
            d = full.json()
            fixed = sorted({e["fixed"] for a in d.get("affected", []) for rng in a.get("ranges", []) for e in rng.get("events", []) if "fixed" in e})
            findings.append({"package": name, "version": version, "id": d["id"], "aliases": d.get("aliases", []),
                             "summary": (d.get("summary") or d.get("details", ""))[:200], "severity": _severity(d), "fixed_in": fixed})
    return findings


def vuln_policy(findings: list[dict[str, Any]], allowlist: dict[str, Any], today: dt.date | None = None) -> dict[str, Any]:
    today = today or dt.date.today()
    allowed = {a["id"]: a for a in allowlist.get("entries", [])}
    blocking, accepted = [], []
    for f in findings:
        if SEVERITY_ORDER.get(f["severity"], 3) < 3:   # UNKNOWN is treated as HIGH
            continue
        a = allowed.get(f["id"])
        if a and dt.date.fromisoformat(a["expires"]) >= today and a.get("justification"):
            accepted.append({**f, "justification": a["justification"], "expires": a["expires"]})
        else:
            blocking.append(f)
    return {"ok": not blocking, "blocking": blocking, "accepted_risk": accepted, "total_findings": len(findings)}


def deterministic_zip(out: str | Path, entries: Iterable[tuple[str, bytes]]) -> str:
    """Write a zip whose bytes depend only on (name, content) pairs; returns its sha256."""
    items = sorted(entries, key=lambda e: e[0])
    names = [n for n, _ in items]
    if len(names) != len(set(names)):
        raise ValueError("duplicate archive member names")
    with zipfile.ZipFile(out, "w") as z:
        for name, data in items:
            info = zipfile.ZipInfo(name, date_time=FIXED_ZIP_TIME)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = (0o100644 & 0xFFFF) << 16
            info.create_system = 3
            z.writestr(info, data, compresslevel=9)
    return sha256_file(out)


def provenance_statement(subject_name: str, subject_sha256: str, commit: str, repo: str,
                         materials: dict[str, str], builder_id: str, invocation_id: str) -> dict[str, Any]:
    return {
        "_type": INTOTO_STATEMENT,
        "subject": [{"name": subject_name, "digest": {"sha256": subject_sha256}}],
        "predicateType": SLSA_PREDICATE,
        "predicate": {
            "buildDefinition": {
                "buildType": BUILD_TYPE,
                "externalParameters": {"repository": repo, "ref": commit},
                "resolvedDependencies": [{"uri": f"git+{repo}@{commit}", "digest": {"gitCommit": commit}}]
                + [{"uri": k, "digest": {"sha256": v}} for k, v in sorted(materials.items())],
            },
            "runDetails": {"builder": {"id": builder_id},
                           "metadata": {"invocationId": invocation_id, "startedOn": source_date().strftime("%Y-%m-%dT%H:%M:%SZ")}},
        },
    }


def verify_provenance(statement: dict[str, Any], artifact: str | Path, expected_commit: str,
                      expected_materials: dict[str, str] | None = None) -> list[str]:
    """Return a list of problems (empty = verified)."""
    problems = []
    if statement.get("_type") != INTOTO_STATEMENT:
        problems.append("not an in-toto v1 statement")
    if statement.get("predicateType") != SLSA_PREDICATE:
        problems.append("predicate is not SLSA provenance v1")
    digest = sha256_file(artifact)
    subjects = statement.get("subject", [])
    if not any(s.get("digest", {}).get("sha256") == digest for s in subjects):
        problems.append(f"artifact sha256 {digest[:12]}… matches no subject")
    bd = statement.get("predicate", {}).get("buildDefinition", {})
    if bd.get("externalParameters", {}).get("ref") != expected_commit:
        problems.append("provenance commit does not match the commit being deployed")
    if expected_materials:
        recorded = {d["uri"]: d["digest"].get("sha256") for d in bd.get("resolvedDependencies", []) if "sha256" in d.get("digest", {})}
        for uri, sha in expected_materials.items():
            if recorded.get(uri) != sha:
                problems.append(f"material {uri} digest mismatch")
    return problems
